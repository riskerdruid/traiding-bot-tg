TOPICS_BY_ID = {t["id"]: t for t in TOPICS}


def topic_list() -> list[dict]:
    """Короткий список тем — для меню."""
    return [
        {"id": t["id"], "icon": t["icon"], "title": t["title"], "summary": t["summary"]}
        for t in TOPICS
    ]


def render_topic_text(topic_id: str) -> str | None:
    """Тема в виде HTML-сообщения для Telegram."""
    topic = TOPICS_BY_ID.get(topic_id)
    if topic is None:
        return None

    lines = [f"{topic['icon']} <b>{topic['title']}</b>", ""]
    for block in topic["blocks"]:
        kind = block["type"]
        if kind == "text":
            lines.append(block["text"])
        elif kind == "steps":
            for i, item in enumerate(block["items"], 1):
                lines.append(f"{i}. {item}")
        elif kind == "list":
            for item in block["items"]:
                lines.append(f"• {item}")
        elif kind == "note":
            lines.append(f"<i>💡 {block['text']}</i>")
        elif kind == "warn":
            lines.append(f"<i>⚠️ {block['text']}</i>")
        elif kind == "code":
            lines.append(f"<pre>{_escape(block['text'])}</pre>")
        lines.append("")
    return "\n".join(lines).strip()


def _escape(text: str) -> str:
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    )
