TOPICS_BY_ID = {t["id"]: t for t in TOPICS}


def topic_list() -> list[dict]:
    """Короткий список тем — для кнопок."""
    return [{"id": t["id"], "icon": t["icon"], "title": t["title"]} for t in TOPICS]


def render_topic_text(topic_id: str) -> str | None:
    """Тема в виде готового сообщения."""
    topic = TOPICS_BY_ID.get(topic_id)
    if topic is None:
        return None
    return f"{topic['icon']} <b>{topic['title']}</b>\n\n{topic['text']}"


